"""Write the complete retail data catalog (M29c): schema, types, keys, relationships and descriptions.

    cd backend && .venv/bin/python -m retail.export_catalog

Writes backend/catalog/generated/catalog.json (for the model, tools and the /catalog API) and
docs/data-catalog.html (for people). Both come from backend/catalog/*.toml plus the database's own
schema, and a test fails when the committed files are out of date. Neither holds data or row counts.
"""
import argparse
import html
import json
import os
from pathlib import Path

import psycopg

from app import catalog

BACKEND = Path(__file__).resolve().parents[1]
GENERATED_JSON = BACKEND / "catalog" / "generated" / "catalog.json"
HTML_PAGE = BACKEND.parent / "docs" / "data-catalog.html"
DEFAULT_URL = "postgresql://retail_owner:retail_owner_dev_pw@localhost:5433/retail"


def to_json(full):
    tables = {name: {k: v for k, v in t.items() if k != "rows"} for name, t in full.items()}
    return json.dumps({"description": "Retail demo data catalog: tables, columns, types, keys, relationships "
                                      "and meanings. Generated by retail.export_catalog; do not edit by hand.",
                       "tables": tables}, indent=2, ensure_ascii=False) + "\n"


