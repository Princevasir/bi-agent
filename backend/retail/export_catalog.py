def _e(text):
    return html.escape(str(text))


def _table_card(t):
    rows = []
    for c in t["columns"]:
        tags = ("<span class='tag pk'>PK</span>" if c["primary_key"] else "") + \
               (f"<span class='tag fk'>FK</span>" if c["references"] else "") + \
               ("<span class='tag pii'>Personal data</span>" if c["pii"] else "")
        extra = []
        if c["references"]:
            extra.append(f"References <code>{_e(c['references'])}</code>.")
        if c["values"]:
            extra.append("Values: " + ", ".join(f"<code>{_e(v)}</code>" for v in c["values"]) + ".")
        if c["unit"]:
            extra.append(f"Unit: {_e(c['unit'])}.")
        rows.append(f"<tr><td><code>{_e(c['name'])}</code> {tags}</td><td><code>{_e(c['type'])}</code>"
                    f"{'' if c['nullable'] else ' <span class=muted>not null</span>'}</td>"
                    f"<td>{_e(c['description'])} {' '.join(extra)}</td></tr>")
    rel = []
    if t["foreign_keys"]:
        rel.append("Points to: " + ", ".join(f"<code>{_e(f['column'])}</code> → <a href='#{_e(f['table'])}'>"
                                              f"{_e(f['table'])}</a>" for f in t["foreign_keys"]))
    if t["referenced_by"]:
        rel.append("Referenced by: " + ", ".join(f"<a href='#{_e(r['table'])}'>{_e(r['table'])}</a>."
                                                 f"<code>{_e(r['column'])}</code>" for r in t["referenced_by"]))
    caveats = "".join(f"<li>{_e(c)}</li>" for c in t["caveats"])
    return (f"<div class='card' id=\"{_e(t['name'])}\"><h3><code>{_e(t['name'])}</code></h3>"
            f"<p class='meta'>{_e(t['description'])}</p>"
            f"<p class='meta'><b>Grain:</b> {_e(t['grain'])} <b>Primary key:</b> "
            f"<code>{_e(', '.join(t['primary_key']))}</code></p>"
            + "".join(f"<p class='meta'>{r}</p>" for r in rel)
            + (f"<p class='meta'><b>Watch out:</b></p><ul>{caveats}</ul>" if caveats else "")
            + "<div class='tablewrap'><table><thead><tr><th>Column</th><th>Type</th><th>Meaning</th></tr></thead>"
            f"<tbody>{''.join(rows)}</tbody></table></div></div>")


def render_html(full):
    domains = []
    for t in full.values():
        if t["domain"] not in domains:
            domains.append(t["domain"])
    nav = "".join(f"<b>{_e(d)}</b>" + "".join(f"<a href='#{_e(n)}'>{_e(n)}</a>" for n, t in full.items()
                                                if t["domain"] == d) for d in domains)
    sections = "".join(f"<h2>{_e(d)}</h2>" + "".join(_table_card(t) for t in full.values() if t["domain"] == d)
                       for d in domains)
    columns = sum(len(t["columns"]) for t in full.values())
    return ("<!doctype html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">"
            "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">"
            f"<title>Data catalog</title><style>{STYLE}</style></head><body><main>"
            "<h1>Data catalog: retail demo data</h1>"
            f"<p class='lede'>{len(full)} tables and {columns} columns: what each one means, its type, keys and "
            "relationships. Generated by <code>python -m retail.export_catalog</code> from "
            "<code>backend/catalog/*.toml</code> and the database schema; do not edit by hand. "
            "Columns marked Personal data are hidden from analysts and limited users.</p>"
            f"<nav>{nav}</nav>{sections}</main></body></html>\n")


def main(argv=None):
    p = argparse.ArgumentParser(description="Write the retail data catalog (JSON and HTML).")
    p.add_argument("--url", default=os.getenv("RETAIL_OWNER_URL", DEFAULT_URL))
    args = p.parse_args(argv)

    def run(sql, params=None):
        with psycopg.connect(args.url) as conn:
            return conn.execute(sql, params).fetchall()

    full = catalog.merged(catalog.load(), catalog.introspect(run))
    GENERATED_JSON.parent.mkdir(parents=True, exist_ok=True)
    GENERATED_JSON.write_text(to_json(full))
    HTML_PAGE.write_text(render_html(full))
    print(f"{len(full)} tables, {sum(len(t['columns']) for t in full.values())} columns")
    print(f"wrote {GENERATED_JSON}\nwrote {HTML_PAGE}")


if __name__ == "__main__":
    main()
